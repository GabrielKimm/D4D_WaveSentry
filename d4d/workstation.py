def label(text, role='muted'):
    result = QLabel(text)
    result.setObjectName(role)
    return result


def scroller(widget):
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    scroll.setWidget(widget)
    return scroll


def action(window, menu, title, shortcut, callback, checkable=False):
    result = QAction(title, window)
    result.setShortcut(shortcut)
    result.setCheckable(checkable)
    result.triggered.connect(callback)
    menu.addAction(result)
    return result


